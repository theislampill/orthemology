"""Primitive intrinsic knowing with non-efficient truth-relations.
Original cognition is represented, not generated by a created mechanism.
"""
from dataclasses import dataclass,asdict
from itertools import product
from pathlib import Path
from datetime import datetime,timezone
import json,sys
from joint_interpretation import powerset,choose_own_activity,execute_intentions

@dataclass(frozen=True)
class StandingKnowledge:
    bearer:str
    token:str
    intrinsic:bool=True


def forecast_from_intrinsic_reasons(q,commands):
    # It reasons from the assumed known intrinsic choice policies and law.
    # It does not read the peer's actual execution or an actual created event.
    predicted_acts=[choose_own_activity(g,q,commands) for g in ['A','B']]
    events,supports,rules,satisfied=execute_intentions(predicted_acts)
    return {'commands':{a.bearer:tuple(sorted(a.exact_created_target)) for a in predicted_acts},'events':events,'supports':{e:tuple(sorted(v)) for e,v in supports.items()},'rules':rules,'exact_intentions':satisfied}


def actual_execution(acts):
    events,supports,rules,satisfied=execute_intentions(acts)
    return {'commands':{a.bearer:tuple(sorted(a.exact_created_target)) for a in acts},'events':events,'supports':{e:tuple(sorted(v)) for e,v in supports.items()},'rules':rules,'exact_intentions':satisfied}


def has_foreign_donor(knowledge,bearer,edges):
    # Edges here are specifically efficient donation; inherence and truth
    # correspondence are separate relation sorts and cannot enter this graph.
    backwards={}
    for a,b in edges:backwards.setdefault(b,set()).add(a)
    todo=[knowledge];seen=set()
    while todo:
        x=todo.pop()
        for parent in backwards.get(x,[]):
            if parent not in seen:seen.add(parent);todo.append(parent)
    return any(x.startswith('B_') for x in seen) if bearer=='A' else any(x.startswith('A_') for x in seen)


def run():
    commands=powerset(('e0','e1'));targets=[q for q in commands if q]
    K={g:StandingKnowledge(g,'K_'+g) for g in ['A','B']}
    # Same standing attribute tokens exist in every represented reason-context.
    # These contexts are not asserted to be alternatives under one FULLY fixed
    # necessary intrinsic nature; full reason-context fixation is respected.
    worlds=[]
    for q in targets:
        predictions={g:forecast_from_intrinsic_reasons(q,commands) for g in ['A','B']}
        acts=[choose_own_activity(g,q,commands) for g in ['A','B']]
        actual=actual_execution(acts)
        truth=all(predictions[g]==actual for g in K)
        worlds.append({'reason_context':tuple(sorted(q)),'standing_knowledge':{g:asdict(v) for g,v in K.items()}, 'forecast_before_actual_execution':predictions,'actual':actual,'factive':truth,'choice_peer_execution_input':False})
    # Knowledge accessibility is derived by equality of the known intrinsic
    # reason-context, not by looking up what facts happened to be true.
    complete=[]
    for i,w in enumerate(worlds):
        accessible=[j for j,v in enumerate(worlds) if w['reason_context']==v['reason_context']]
        complete.append({'world':i,'accessible_from_known_reason_context':accessible,'all_subset_propositions_known_iff_true':all(all(j in prop for j in accessible)==(i in prop) for mask in range(1<<len(worlds)) for prop in [{j for j in range(len(worlds)) if mask>>j&1}])})
    q=targets[-1];pred=forecast_from_intrinsic_reasons(q,commands)
    a=choose_own_activity('A',q,commands);b=choose_own_activity('B',q,commands)
    suppressed=actual_execution([a])
    efficient=[('A_act','e'),('B_act','e')]
    donor=efficient+[('B_act','K_A')]
    return {'schema':'primitive-intrinsic-knower/1','run_utc':datetime.now(timezone.utc).isoformat(),
      'relation_types':{'inherence':[['K_A','A'],['K_B','B']],'efficient_productive':efficient,'truth_correspondence':'predicted content equals represented actual facts; this relation is not an efficient edge','intrinsic_reason_to_choice':'choice(Q) issues own fullQ independently of peer actual execution'},
      'worlds':worlds,'complete_knowledge_checks':complete,
      'original_nonreceipt_represented':{g:not has_foreign_donor('K_'+g,g,efficient) for g in K},
      'foreign_donation_negative_control_detected':has_foreign_donor('K_A','A',donor),
      'suppression_control':{'frozen_A_command':tuple(sorted(a.exact_created_target)),'fixed_predicted_content_factive':pred==suppressed,'covarying_true_content_available':suppressed,'interpretation':'Suppression overrides a known intrinsic policy and is not certified admissible. Updated relational truth content need not be efficient receipt, but does not follow from the unchanged ordinary-case forecast.'},
      'scope':{'interpreted':'standing intrinsic knowledge, unreceived in typed efficient graph, distinct inherence/truth relations, deductive actual foreknowledge, introspection, full information over represented facts, independent productive choice','not_required':'a created cognitive mechanism or efficient production of the original knowing attribute','not_established':'actual-world warrant or metaphysical feasibility of plural necessary originals; unrestricted knowledge of every fact beyond represented domain; source approval of the coalescent productive mode'}}

